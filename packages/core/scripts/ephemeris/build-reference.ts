/**
 * Regenerates `tests/horizons-reference.json`: positions from NASA/JPL Horizons
 * (DE441) that the tests hold the ephemeris to. Independent of the tables in
 * `src/ephemeris/data/`, except in so far as both come from Horizons for the
 * integrated bodies — whose test instants never coincide with a checkpoint.
 *
 * Usage: bun packages/core/scripts/ephemeris/build-reference.ts
 */
import { writeFile } from 'node:fs/promises'
import { join } from 'node:path'
import { chunks, horizons, horizonsRows } from './lib/sources.ts'

const OUTPUT = join(import.meta.dirname, '..', '..', 'tests', 'horizons-reference.json')

/** Horizons identifiers: body centres for the Sun, Moon, Mercury and Venus; system barycentres beyond. */
const BODIES = {
  Sun: '10',
  Moon: '301',
  Mercury: '199',
  Venus: '299',
  Mars: '4',
  Jupiter: '5',
  Saturn: '6',
  Uranus: '7',
  Neptune: '8',
  Pluto: '9',
  Chiron: '2060;',
} as const

/** Julian days (TT) of Chiron's coverage: 1900 to 2100. */
const CHIRON_SPAN = [2415020.5, 2488069.5]

/** `count` instants spread over [start, end] at uneven fractions of a day. */
function instants(start: number, end: number, count: number): number[] {
  return Array.from({ length: count }, (_, i) => {
    const day = Math.round(start + (end - start) * (i + 0.5) / count)
    return Number((day + ((i * 7919 + 123) % 1000) / 1000).toFixed(3))
  })
}

/** An observer table for the geocentre at TT instants; returns the two angle columns in degrees. */
async function observe(command: string, jds: readonly number[], quantity: string): Promise<[number, number][]> {
  const result: [number, number][] = []
  for (const batch of chunks(jds, 40)) {
    const text = await horizons({
      COMMAND: `'${command}'`,
      EPHEM_TYPE: "'OBSERVER'",
      CENTER: "'500@399'",
      TLIST: batch.map(jd => `'${jd}'`).join(','),
      TLIST_TYPE: "'JD'",
      TIME_TYPE: "'TT'",
      QUANTITIES: `'${quantity}'`,
      ANG_FORMAT: "'DEG'",
      EXTRA_PREC: "'YES'",
      CSV_FORMAT: "'YES'",
    })
    const rows = horizonsRows(text)
    if (rows.length !== batch.length) throw new Error(`Horizons returned ${rows.length} of ${batch.length} rows for ${command}`)
    for (const row of rows) result.push([Number(row[3]), Number(row[4])])
  }
  return result
}

async function collect(jds: readonly number[], quantity: string) {
  const bodies: Record<string, ([number, number] | null)[]> = {}
  for (const [name, command] of Object.entries(BODIES)) {
    if (name !== 'Chiron') {
      bodies[name] = await observe(command, jds, quantity)
      continue
    }
    const covered = jds.filter(jd => jd > CHIRON_SPAN[0] && jd < CHIRON_SPAN[1])
    const values = await observe(command, covered, quantity)
    bodies[name] = jds.map(jd => values[covered.indexOf(jd)] ?? null)
  }
  return { jd: jds, bodies }
}

/**
 * Venus around its superior conjunction of 4 June 2024, when it passed behind
 * the Sun: the bending of its light by the Sun reaches 0.7″ at the limb.
 */
const CONJUNCTION = [2460464.9, 2460465.4, 2460465.9, 2460466.1, 2460466.3, 2460466.6, 2460467.1, 2460467.9]

const reference = {
  source: 'NASA/JPL Horizons API (https://ssd.jpl.nasa.gov/horizons/), DE441; Chiron: JPL small-body solution. '
    + 'Geocentric, instants in Terrestrial Time. Generated by scripts/ephemeris/build-reference.ts.',
  // Quantity 31: apparent ecliptic longitude and latitude of date (IAU 1976/80 precession and nutation), degrees.
  apparent: await collect(instants(2415021, 2488069, 24), '31'),
  // Quantity 1: astrometric right ascension and declination (ICRF, light-time corrected), degrees.
  astrometric: await collect(instants(1721500, 2817000, 40), '1'),
  // Quantity 31 again, for Venus alone, close to and behind the Sun.
  conjunction: { jd: CONJUNCTION, venus: await observe(BODIES.Venus, CONJUNCTION, '31') },
}

const json = JSON.stringify(reference)
  .replace(/"(source|apparent|astrometric|conjunction)":/g, '\n  "$1": ')
  .replace(/"(jd|bodies|venus)":/g, '\n    "$1": ')
  .replace(/"([A-Z][a-z]+)":\[\[/g, '\n      "$1": [[')
  .replace(/\}\}$/, '}\n}')
await writeFile(OUTPUT, `${json}\n`)
console.log(`${OUTPUT}: ${(json.length / 1024).toFixed(1)} KB`)
