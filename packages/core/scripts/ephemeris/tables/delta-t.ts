/**
 * Generates `src/ephemeris/data/delta-t.ts`: observed TT − UT1 at the start of
 * each year since 1900, from the U.S. Naval Observatory series.
 */
import { readSource } from '../lib/sources.ts'

const FIRST_YEAR = 1900

export async function buildDeltaT(): Promise<string> {
  const values = new Map<number, number>()

  // historic_deltat.data: "year.fraction  TDT-UT1  error  LOD  error", half-yearly, 1657-1984.
  for (const line of (await readSource('deltat', 'historic_deltat.data')).split('\n')) {
    const fields = line.trim().split(/\s+/).map(Number)
    if (fields.length >= 2 && Number.isInteger(fields[0]) && fields[0] >= FIRST_YEAR) {
      values.set(fields[0], fields[1])
    }
  }
  // deltat.data: "year month day  TT-UT1", monthly since 1973; it supersedes the historic file.
  let latest = { year: 0, month: 0, value: 0 }
  for (const line of (await readSource('deltat', 'deltat.data')).split('\n')) {
    const [year, month, day, value] = line.trim().split(/\s+/).map(Number)
    if (!Number.isFinite(value) || day !== 1) continue
    if (month === 1) values.set(year, value)
    latest = { year, month, value }
  }

  const lastYear = Math.max(...values.keys())
  const table: number[] = []
  for (let year = FIRST_YEAR; year <= lastYear; year++) {
    const value = values.get(year)
    if (value === undefined) throw new Error(`no ΔT value for ${year}`)
    table.push(value)
  }

  const lines: string[] = []
  for (let i = 0; i < table.length; i += 10) {
    lines.push(`  ${table.slice(i, i + 10).map(value => Number(value.toFixed(2))).join(', ')},`)
  }

  return `/**
 * Observed ΔT = TT − UT1 in seconds at 0h on 1 January of each year.
 *
 * GENERATED by scripts/ephemeris/build-tables.ts — do not edit by hand.
 *
 * Source: U.S. Naval Observatory, Earth Orientation Department,
 * https://maia.usno.navy.mil/ser7/historic_deltat.data (to 1973) and
 * https://maia.usno.navy.mil/ser7/deltat.data (from 1974; latest entry used
 * here: ${latest.year}-${String(latest.month).padStart(2, '0')}, ${latest.value} s).
 */
export const DELTA_T_FIRST_YEAR = ${FIRST_YEAR}

export const DELTA_T_YEARLY: readonly number[] = [
${lines.join('\n')}
]
`
}
