/**
 * Generates `src/ephemeris/data/nutation.ts`: the largest lunisolar terms of
 * the IAU 2000A_R06 nutation series (IERS Conventions 2010, Tables 5.3a/5.3b).
 */
import { readSource } from '../lib/sources.ts'

/** Terms below this amplitude (microarcseconds) are dropped. */
const THRESHOLD_UAS = 100
/** Secular (per-century) parts are kept when they can reach the threshold within this many centuries. */
const SPAN_CENTURIES = 20

interface Row {
  /** In-phase coefficient (sin for longitude, cos for obliquity). */
  inPhase: number
  /** Out-of-phase coefficient (cos for longitude, sin for obliquity). */
  outOfPhase: number
}

type Table = Map<string, [Row, Row]> // key: "l l' F D Om" → [constant part, per-century part]

/**
 * Parse one of the two tables. Each has a `j = 0` section (constant amplitudes)
 * and a `j = 1` section (amplitudes multiplied by t). Columns: index, two
 * amplitudes, then 14 integer multipliers (5 lunisolar, 9 planetary).
 */
function parse(text: string, inPhaseColumn: 1 | 2): Table {
  const table: Table = new Map()
  let section = -1
  for (const line of text.split('\n')) {
    const header = /^\s*j = (\d)/.exec(line)
    if (header) {
      section = Number(header[1])
      continue
    }
    const fields = line.trim().split(/\s+/)
    if (section < 0 || section > 1 || fields.length !== 17 || !/^\d+$/.test(fields[0])) continue
    const multipliers = fields.slice(3).map(Number)
    if (multipliers.slice(5).some(value => value !== 0)) continue // planetary term
    const key = multipliers.slice(0, 5).join(' ')
    const entry = table.get(key) ?? [{ inPhase: 0, outOfPhase: 0 }, { inPhase: 0, outOfPhase: 0 }]
    entry[section].inPhase += Number(fields[inPhaseColumn])
    entry[section].outOfPhase += Number(fields[inPhaseColumn === 1 ? 2 : 1])
    table.set(key, entry)
  }
  return table
}

export async function buildNutation(): Promise<string> {
  // Table 5.3a lists (A sin, A" cos); Table 5.3b lists (B" sin, B cos).
  const longitude = parse(await readSource('iers', 'tab5.3a.txt'), 1)
  const obliquity = parse(await readSource('iers', 'tab5.3b.txt'), 2)

  const none: [Row, Row] = [{ inPhase: 0, outOfPhase: 0 }, { inPhase: 0, outOfPhase: 0 }]
  const reach = (rows: [Row, Row]) => Math.max(
    Math.abs(rows[0].inPhase), Math.abs(rows[0].outOfPhase),
    Math.abs(rows[1].inPhase) * SPAN_CENTURIES, Math.abs(rows[1].outOfPhase) * SPAN_CENTURIES,
  )
  const keys = [...new Set([...longitude.keys(), ...obliquity.keys()])]
    .map(key => ({ key, psi: longitude.get(key) ?? none, eps: obliquity.get(key) ?? none }))
    .filter(({ psi, eps }) => Math.max(reach(psi), reach(eps)) >= THRESHOLD_UAS)
    .sort((p, q) => reach(q.psi) + reach(q.eps) - reach(p.psi) - reach(p.eps))

  const number = (value: number) => String(Number(value.toFixed(1)))
  const rows = keys.map(({ key, psi, eps }) => `  [${[
    ...key.split(' '),
    number(psi[0].inPhase), number(psi[1].inPhase), number(psi[0].outOfPhase),
    number(eps[0].inPhase), number(eps[1].inPhase), number(eps[0].outOfPhase),
  ].join(', ')}],`)

  return `/**
 * Nutation series, truncated.
 *
 * GENERATED by scripts/ephemeris/build-tables.ts — do not edit by hand.
 *
 * Source: IERS Conventions (2010), IERS Technical Note 36, Chapter 5, Tables
 * 5.3a and 5.3b (IAU 2000A_R06 nutation in longitude and obliquity),
 * https://iers-conventions.obspm.fr/content/chapter5/additional_info/
 *
 * The ${keys.length} lunisolar terms of at least ${THRESHOLD_UAS / 1000} milliarcsecond. Each row holds the
 * multipliers of the Delaunay arguments (l, l', F, D, Ω) and, in microarcseconds:
 *   Δψ: sin coefficient, its change per Julian century, cos coefficient
 *   Δε: cos coefficient, its change per Julian century, sin coefficient
 */
export const NUTATION_TERMS: readonly (readonly number[])[] = [
${rows.join('\n')}
]
`
}
