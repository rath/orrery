/**
 * Generates `src/ephemeris/data/checkpoints.ts`: states of the outer planets
 * and Chiron from JPL Horizons, from which the integrator starts.
 */
import { HORIZONS_ID, horizonsStates } from '../lib/horizons-vectors.ts'
import { innerBarycentre, integrate } from '../../../src/ephemeris/integrator.ts'
import type { CheckpointTable, IntegratedBody } from '../../../src/ephemeris/integrator.ts'
import type { State } from '../../../src/ephemeris/planets.ts'
import { J2000 } from '../../../src/ephemeris/time.ts'

interface Plan {
  name: string
  comment: string
  bodies: IntegratedBody[]
  /** Days between checkpoints. */
  interval: number
  /** Checkpoints run from J2000 + first·interval to J2000 + last·interval. */
  first: number
  last: number
  /**
   * Largest discrepancy tolerated, in arcseconds as seen from the Earth, when
   * one checkpoint is integrated all the way to the next. In use an
   * integration covers at most half that distance.
   */
  tolerance: number
}

const PLANS: Plan[] = [
  {
    name: 'OUTER_CHECKPOINTS',
    comment: 'Jupiter to Pluto, 28 BCE to 3040 CE.',
    bodies: ['Jupiter', 'Saturn', 'Uranus', 'Neptune', 'Pluto'],
    interval: 10000,
    first: -74,
    last: 38,
    tolerance: 0.25,
  },
  {
    name: 'CHIRON_CHECKPOINTS',
    comment: 'Chiron with the planets that perturb it, 1890 to 2109.',
    bodies: ['Jupiter', 'Saturn', 'Uranus', 'Neptune', 'Pluto', 'Chiron'],
    interval: 4000,
    first: -10,
    last: 10,
    tolerance: 0.15,
  },
]

const ARCSEC_PER_RADIAN = 206264.806

async function buildTable(plan: Plan): Promise<{ table: CheckpointTable; worst: number[] }> {
  const epochs: number[] = []
  for (let k = plan.first; k <= plan.last; k++) epochs.push(J2000 + k * plan.interval)

  // Horizons serves one request at a time, so fetch the bodies in turn.
  const heliocentric: State[][] = []
  for (const body of plan.bodies) heliocentric.push(await horizonsStates(HORIZONS_ID[body], epochs))

  // The integrator works about the centre of mass of the Sun and inner planets.
  const perEpoch = epochs.map((jd, e) => {
    const centre = innerBarycentre(jd, 0)
    return plan.bodies.flatMap((_, b) => heliocentric[b][e].map((value, i) => value - centre[i]))
  })

  // Self-check: integrating from each checkpoint must land on the next one.
  const worst = plan.bodies.map(() => 0)
  for (let e = 0; e + 1 < epochs.length; e++) {
    const single = { epoch: epochs[e], interval: plan.interval, bodies: plan.bodies, states: perEpoch[e] }
    const { state } = integrate(single, epochs[e + 1])
    plan.bodies.forEach((body, b) => {
      const expected = perEpoch[e + 1].slice(6 * b, 6 * b + 3)
      const miss = Math.hypot(state[6 * b] - expected[0], state[6 * b + 1] - expected[1], state[6 * b + 2] - expected[2])
      const nearestToEarth = Math.hypot(expected[0], expected[1], expected[2]) - 1
      const angle = miss / nearestToEarth * ARCSEC_PER_RADIAN
      worst[b] = Math.max(worst[b], angle)
      if (angle > plan.tolerance) {
        throw new Error(`${body}: integrating JD ${epochs[e]} → ${epochs[e + 1]} misses by ${angle.toFixed(3)}″`)
      }
    })
  }

  return {
    table: { epoch: epochs[0], interval: plan.interval, bodies: plan.bodies, states: perEpoch.flat() },
    worst,
  }
}

/** Positions to 10⁻¹¹ AU, velocities to 10⁻¹⁴ AU/day. */
function printState(values: readonly number[]): string {
  return values.map((value, i) => String(Number(value.toFixed(i % 6 < 3 ? 11 : 14)))).join(', ')
}

export async function buildCheckpoints(): Promise<string> {
  const sections: string[] = []
  for (const plan of PLANS) {
    const { table, worst } = await buildTable(plan)
    const width = 6 * plan.bodies.length
    const rows: string[] = []
    for (let offset = 0; offset < table.states.length; offset += width) {
      rows.push(`    ${printState(table.states.slice(offset, offset + width))},`)
    }
    const check = plan.bodies.map((body, b) => `${body} ${worst[b].toFixed(3)}″`).join(', ')
    sections.push(`/**
 * ${plan.comment}
 * Integrating each checkpoint to the next reproduces it within: ${check}
 * (as seen from the Earth; in use an integration spans at most half an interval).
 */
export const ${plan.name}: CheckpointTable = {
  epoch: ${table.epoch},
  interval: ${table.interval},
  bodies: [${plan.bodies.map(body => `'${body}'`).join(', ')}],
  states: [
${rows.join('\n')}
  ],
}`)
  }

  return `/**
 * Starting states for the numerical integration of the outer solar system.
 *
 * GENERATED by scripts/ephemeris/build-tables.ts — do not edit by hand.
 *
 * Source: NASA/JPL Horizons (https://ssd.jpl.nasa.gov/horizons/), planetary
 * ephemeris DE441 and, for Chiron, small-body orbit solution JPL#171;
 * geometric heliocentric states of the system barycentres of Jupiter, Saturn,
 * Uranus, Neptune and Pluto, and of (2060) Chiron.
 *
 * Each row is one epoch: per body, position (AU) and velocity (AU/day) in the
 * J2000 ecliptic frame, relative to the centre of mass of the Sun and the
 * inner planets.
 */
import type { CheckpointTable } from '../integrator.ts'

${sections.join('\n\n')}
`
}
